#!/usr/bin/env python3
"""Refresh or check the KEV and EPSS context for every hunt that covers a CVE.

Hunt Lab keeps exploitation context for each hunt's CVEs in
``hunts/<YYYY>/<YYYY-MM-DD>-<slug>/cve-context.yaml`` and in a generated table in
the top-level README. This script owns both. It uses only the Python standard
library and two free, public feeds:

* CISA Known Exploited Vulnerabilities (KEV) catalogue, JSON feed. KEV is a
  yes/no list of CVEs with evidence of exploitation in the wild, not a score.
* FIRST Exploit Prediction Scoring System (EPSS) API. EPSS is a probability
  (0 to 1) that a CVE will see exploitation activity in the next 30 days, with
  a percentile against all scored CVEs. It changes daily.

Usage:
    python3 scripts/refresh_kev_epss.py               # fetch live data, rewrite files
    python3 scripts/refresh_kev_epss.py --check       # offline: validate files and README table (CI)
    python3 scripts/refresh_kev_epss.py --allow-null  # let a missing EPSS row replace an existing score

Which CVEs a hunt covers comes from three places, merged: the ``cve.YYYY-NNNNN``
tags in its ``rule.yml``, the CVE IDs in the "CVEs" row of its ``README.md``,
and any ``- cve:`` entries already in its ``cve-context.yaml``. Hunts with no
CVE get no file and show as "n/a" in the README table.

Safety: every output (hunt files and README) is built in memory and checked
before anything is written, so a failed run changes nothing. The FIRST EPSS API
answers an unknown CVE with an empty result rather than an error, so by default
an existing score is never replaced by null: the old score and its dates are
kept and a warning is printed. If FIRST returns no row for every CVE, and at
least one of them already has a score, that is treated as an outage, not a gap:
nothing is written and the script exits with code 3, even with --allow-null.

Exit codes:
    0  success (refresh written, or --check passed)
    1  --check found a problem, or a refresh failed (network, feed format, local
       file); nothing was written
    2  bad command-line arguments (argparse)
    3  EPSS outage: FIRST returned no score for any CVE; nothing was written

Licence: MIT (see LICENSE).
"""
from __future__ import annotations

import argparse
import datetime as dt
import http.client
import json
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
HUNTS = ROOT / "hunts"
README = ROOT / "README.md"
# .yaml, not .yml: sigma-cli only collects *.yml under hunts/, so this file is not read as a rule.
CONTEXT_NAME = "cve-context.yaml"

KEV_URL = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json"
KEV_PAGE = "https://www.cisa.gov/known-exploited-vulnerabilities-catalog"
EPSS_URL = "https://api.first.org/data/v1/epss?cve="
EPSS_PAGE = "https://www.first.org/epss/"
USER_AGENT = "Cyber-Threat.net Hunt Lab KEV/EPSS refresh (+https://github.com/CyberThreatNet/hunt-lab)"

START = "<!-- kev-epss:start (generated by scripts/refresh_kev_epss.py; do not edit by hand) -->"
END = "<!-- kev-epss:end -->"

CVE_RE = re.compile(r"^CVE-\d{4}-\d{4,}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
README_CVES_ROW_RE = re.compile(r"^\|\s*\*\*CVEs\*\*\s*\|(.*)\|\s*$", re.MULTILINE)
CVE_ANY_RE = re.compile(r"CVE-\d{4}-\d{4,}")
RULE_TAG_RE = re.compile(r"^\s*-\s*cve\.(\d{4}-\d{4,})\s*$", re.MULTILINE)
CTX_CVE_RE = re.compile(r"^\s*-\s*cve:\s*'?(CVE-\d{4}-\d{4,})'?\s*$", re.MULTILINE)

# Field order in each CVE entry. Every field is always present.
FIELDS = (
    "cve",
    "kev_listed",
    "kev_date_added",
    "kev_due_date",
    "kev_ransomware",
    "kev_catalog_version",
    "kev_checked",
    "epss",
    "epss_percentile",
    "epss_date",
    "epss_checked",
    "epss_note",
)

HEADER = """\
# KEV and EPSS context for the CVEs this hunt covers.
# Generated by scripts/refresh_kev_epss.py. Do not edit values by hand: run the script.
# kev_*  : CISA Known Exploited Vulnerabilities catalogue. A yes/no list, not a score.
#          kev_ransomware copies knownRansomwareCampaignUse (Known or Unknown).
#          kev_* dates are null when the CVE is not in KEV.
# epss*  : FIRST EPSS. Probability (0-1) of exploitation activity in the next 30 days,
#          and its percentile among all scored CVEs. Changes daily; read with epss_date.
#          null with an epss_note when FIRST has not scored the CVE yet.
# *_checked: the date (Europe/London) the feed was read.
"""


# --------------------------------------------------------------------------- hunts

def hunt_dirs() -> list[pathlib.Path]:
    return sorted(p for p in HUNTS.glob("*/*") if p.is_dir())


def rule_cves(hunt: pathlib.Path) -> list[str]:
    rule = hunt / "rule.yml"
    if not rule.exists():
        return []
    return sorted({f"CVE-{m}" for m in RULE_TAG_RE.findall(rule.read_text(encoding="utf-8"))})


def readme_cves(hunt: pathlib.Path) -> list[str]:
    """CVE IDs in the "CVEs" row of the hunt README's summary table."""
    readme = hunt / "README.md"
    if not readme.exists():
        return []
    m = README_CVES_ROW_RE.search(readme.read_text(encoding="utf-8"))
    return sorted(set(CVE_ANY_RE.findall(m.group(1)))) if m else []


def expected_cves(hunt: pathlib.Path) -> list[str]:
    """CVEs the hunt declares outside cve-context.yaml (rule tags and README CVEs row)."""
    return sorted(set(rule_cves(hunt)) | set(readme_cves(hunt)), key=cve_sort_key)


def context_cves(hunt: pathlib.Path) -> list[str]:
    ctx = hunt / CONTEXT_NAME
    if not ctx.exists():
        return []
    return sorted(set(CTX_CVE_RE.findall(ctx.read_text(encoding="utf-8"))))


def cve_sort_key(cve: str) -> tuple[int, int]:
    _, year, num = cve.split("-")
    return int(year), int(num)


# ------------------------------------------------------------------ file format

def fmt_value(value) -> str:
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, float):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def render_context(entries: list[dict]) -> str:
    lines = [HEADER.rstrip("\n"), "cves:"]
    for entry in entries:
        for i, field in enumerate(FIELDS):
            prefix = "    - " if i == 0 else "      "
            lines.append(f"{prefix}{field}: {fmt_value(entry[field])}")
    return "\n".join(lines) + "\n"


def parse_value(raw: str):
    raw = raw.strip()
    if raw == "null":
        return None
    if raw == "true":
        return True
    if raw == "false":
        return False
    if len(raw) >= 2 and raw[0] == raw[-1] == "'":
        return raw[1:-1].replace("''", "'")
    try:
        return float(raw)
    except ValueError:
        raise ValueError(f"unrecognised value {raw!r}") from None


def parse_context(text: str) -> list[dict]:
    """Parse the strict format written by render_context (no external YAML library)."""
    entries: list[dict] = []
    seen_cves = False
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line == "cves:":
            seen_cves = True
            continue
        if not seen_cves:
            raise ValueError(f"line {n}: expected 'cves:' before entries")
        m = re.match(r"^    - (\w+): (.*)$", line) or re.match(r"^      (\w+): (.*)$", line)
        if not m:
            raise ValueError(f"line {n}: unexpected layout: {line!r}")
        key, raw = m.groups()
        if line.startswith("    - "):
            entries.append({})
        elif not entries:
            raise ValueError(f"line {n}: field before first '- cve:' entry")
        if key in entries[-1]:
            raise ValueError(f"line {n}: duplicate field {key}")
        try:
            entries[-1][key] = parse_value(raw)
        except ValueError as exc:
            raise ValueError(f"line {n}: {exc}") from None
    if not seen_cves:
        raise ValueError("missing 'cves:' list")
    return entries


def validate_entry(e: dict) -> list[str]:
    errs = []
    keys = list(e.keys())
    if keys != list(FIELDS):
        missing = [f for f in FIELDS if f not in e]
        extra = [k for k in keys if k not in FIELDS]
        return [f"fields must be exactly {', '.join(FIELDS)} in that order"
                + (f"; missing {missing}" if missing else "") + (f"; unexpected {extra}" if extra else "")]
    cve = e["cve"]
    if not (isinstance(cve, str) and CVE_RE.match(cve)):
        errs.append(f"cve {cve!r} is not CVE-YYYY-NNNN")

    def is_date(v):
        return isinstance(v, str) and DATE_RE.match(v)

    if not isinstance(e["kev_listed"], bool):
        errs.append(f"{cve}: kev_listed must be true or false")
    elif e["kev_listed"]:
        for f in ("kev_date_added", "kev_due_date"):
            if not is_date(e[f]):
                errs.append(f"{cve}: {f} must be a YYYY-MM-DD date when kev_listed is true")
        if e["kev_ransomware"] not in ("Known", "Unknown"):
            errs.append(f"{cve}: kev_ransomware must be Known or Unknown when kev_listed is true")
    else:
        for f in ("kev_date_added", "kev_due_date", "kev_ransomware"):
            if e[f] is not None:
                errs.append(f"{cve}: {f} must be null when kev_listed is false")
    if not (isinstance(e["kev_catalog_version"], str) and re.match(r"^\d{4}\.\d{2}\.\d{2}$", e["kev_catalog_version"])):
        errs.append(f"{cve}: kev_catalog_version must look like YYYY.MM.DD")
    for f in ("kev_checked", "epss_checked"):
        if not is_date(e[f]):
            errs.append(f"{cve}: {f} must be a YYYY-MM-DD date")
    if e["epss"] is None:
        if e["epss_percentile"] is not None or e["epss_date"] is not None:
            errs.append(f"{cve}: epss_percentile and epss_date must be null when epss is null")
        if not (isinstance(e["epss_note"], str) and e["epss_note"]):
            errs.append(f"{cve}: epss_note must explain why epss is null")
    else:
        for f in ("epss", "epss_percentile"):
            if not (isinstance(e[f], float) and 0.0 <= e[f] <= 1.0):
                errs.append(f"{cve}: {f} must be a number from 0 to 1")
        if not is_date(e["epss_date"]):
            errs.append(f"{cve}: epss_date must be a YYYY-MM-DD date")
        if e["epss_note"] is not None:
            errs.append(f"{cve}: epss_note must be null when epss has a value")
    return errs


# --------------------------------------------------------------- README table

def ransomware_text(e: dict) -> str:
    return e["kev_ransomware"] if e["kev_listed"] else "–"


def render_table(rows: list[tuple[pathlib.Path, list[dict]]]) -> str:
    out = [
        START,
        "",
        "| Hunt | CVE | In KEV | KEV added | KEV due | Ransomware use (KEV) | EPSS (0-1) | EPSS percentile (0-100) | Checked |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for hunt, entries in rows:
        rel = hunt.relative_to(ROOT).as_posix()
        link = f"[{hunt.name}]({rel}/)"
        if not entries:
            out.append(f"| {link} | n/a (no CVE) | n/a | | | | | | |")
            continue
        for e in entries:
            if e["epss"] is None:
                epss, pct = "not yet scored", "–"
            else:
                epss, pct = f"{e['epss']:.5f}", f"{e['epss_percentile'] * 100:.2f}"
            checked = e["kev_checked"] if e["kev_checked"] == e["epss_checked"] else f"KEV {e['kev_checked']}, EPSS {e['epss_checked']}"
            out.append(
                f"| {link} | {e['cve']} | {'Yes' if e['kev_listed'] else 'No'} "
                f"| {e['kev_date_added'] or '–'} | {e['kev_due_date'] or '–'} | {ransomware_text(e)} "
                f"| {epss} | {pct} | {checked} (KEV catalogue {e['kev_catalog_version']}) |"
            )
    out += ["", END]
    return "\n".join(out)


class RefreshError(Exception):
    """Any failure that must stop a refresh before anything is written."""


def replace_block(text: str, block: str) -> str:
    start, end = text.find(START), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise RefreshError(f"README.md: generated-table markers not found ({START!r} ... {END!r})")
    return text[:start] + block + text[end + len(END):]


# ------------------------------------------------------------------ live feeds

def get_json(url: str) -> dict:
    """GET a JSON document over HTTPS. Any failure becomes a RefreshError."""
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            final = resp.geturl()
            if not final.startswith("https://"):
                raise RefreshError(f"{url} redirected to a non-HTTPS URL ({final})")
            data = json.load(resp)
    except RefreshError:
        raise
    except (urllib.error.URLError, http.client.HTTPException, OSError, ValueError) as exc:
        # URLError and TimeoutError are OSError subclasses; JSONDecodeError is a ValueError.
        raise RefreshError(f"could not read {url}: {exc}") from None
    if not isinstance(data, dict):
        raise RefreshError(f"{url} did not return a JSON object")
    return data


def fetch_kev() -> tuple[str, dict[str, dict]]:
    data = get_json(KEV_URL)
    try:
        version = data["catalogVersion"]
        vulns = {v["cveID"]: v for v in data["vulnerabilities"]}
    except (KeyError, TypeError) as exc:
        raise RefreshError(f"KEV feed format has changed (missing {exc})") from None
    if not isinstance(version, str) or not version:
        raise RefreshError("KEV feed has no catalogVersion")
    return version, vulns


def fetch_epss(cves: list[str]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for i in range(0, len(cves), 50):
        data = get_json(EPSS_URL + ",".join(cves[i:i + 50]))
        if data.get("status-code") != 200:
            raise RefreshError(f"EPSS API returned status {data.get('status-code')}")
        try:
            for row in data.get("data", []):
                out[row["cve"]] = row
        except (KeyError, TypeError) as exc:
            raise RefreshError(f"EPSS API format has changed (missing {exc})") from None
    return out


# ------------------------------------------------------------------ commands

def collect() -> list[tuple[pathlib.Path, list[str]]]:
    out = []
    for hunt in hunt_dirs():
        cves = sorted(set(expected_cves(hunt)) | set(context_cves(hunt)), key=cve_sort_key)
        out.append((hunt, cves))
    return out


def existing_entries(hunt: pathlib.Path) -> dict[str, dict]:
    ctx = hunt / CONTEXT_NAME
    if not ctx.exists():
        return {}
    text = ctx.read_text(encoding="utf-8")
    try:
        entries = parse_context(text)
    except ValueError as exc:
        raise RefreshError(f"{ctx.relative_to(ROOT)}: cannot read the existing file ({exc}); fix or delete it") from None
    # A seed file (only "- cve:" lines) has no values to keep.
    return {e["cve"]: e for e in entries if not validate_entry(e)}


def build_entry(cve: str, k: dict | None, s: dict | None, old: dict | None, kev_version: str,
                today: str, allow_null: bool, warnings: list[str]) -> dict:
    try:
        entry = {
            "cve": cve,
            "kev_listed": k is not None,
            "kev_date_added": k["dateAdded"] if k else None,
            "kev_due_date": k["dueDate"] if k else None,
            "kev_ransomware": k["knownRansomwareCampaignUse"] if k else None,
            "kev_catalog_version": kev_version,
            "kev_checked": today,
            "epss": float(s["epss"]) if s else None,
            "epss_percentile": float(s["percentile"]) if s else None,
            "epss_date": s["date"] if s else None,
            "epss_checked": today,
            "epss_note": None if s else f"Not yet scored by FIRST EPSS when checked on {today}",
        }
    except (KeyError, TypeError, ValueError) as exc:
        raise RefreshError(f"{cve}: unexpected feed data ({exc!r})") from None
    if s is None and old is not None and old["epss"] is not None and not allow_null:
        for f in ("epss", "epss_percentile", "epss_date", "epss_checked", "epss_note"):
            entry[f] = old[f]
        warnings.append(
            f"{cve}: FIRST EPSS returned no score; kept the previous score {old['epss']} "
            f"(EPSS date {old['epss_date']}, checked {old['epss_checked']}). "
            "Re-run later, or use --allow-null if the CVE really has no score."
        )
    errs = validate_entry(entry)
    if errs:
        raise RefreshError("feed data failed validation: " + "; ".join(errs))
    return entry


EXIT_OK, EXIT_ERROR, EXIT_USAGE, EXIT_EPSS_OUTAGE = 0, 1, 2, 3


class EpssOutage(RefreshError):
    """FIRST returned no row for any CVE, although some already had scores."""


def check_epss_outage(plan, all_cves: list[str], epss: dict) -> None:
    """Raise EpssOutage if every CVE came back empty and at least one had a score before.

    One empty CVE is a gap (a new CVE not scored yet); all of them empty at once,
    including CVEs FIRST has scored before, means the API is not answering properly.
    """
    if not all_cves or any(c in epss for c in all_cves):
        return
    scored_before = any(e["epss"] is not None for hunt, _ in plan for e in existing_entries(hunt).values())
    if scored_before:
        raise EpssOutage(f"FIRST EPSS returned no score for any of the {len(all_cves)} CVE(s), "
                         "including ones it has scored before; treating this as an outage")


def refresh(today: str, allow_null: bool = False) -> int:
    """Fetch, build every output in memory, then write. Any error leaves the tree untouched."""
    warnings: list[str] = []
    try:
        plan = collect()
        all_cves = sorted({c for _, cves in plan for c in cves}, key=cve_sort_key)
        kev_version, kev = fetch_kev()
        epss = fetch_epss(all_cves) if all_cves else {}
        check_epss_outage(plan, all_cves, epss)
        rows, writes, report = [], {}, []
        for hunt, cves in plan:
            old = existing_entries(hunt)
            entries = [build_entry(c, kev.get(c), epss.get(c), old.get(c), kev_version, today, allow_null, warnings)
                       for c in cves]
            rows.append((hunt, entries))
            if entries:
                writes[hunt / CONTEXT_NAME] = render_context(entries)
                for e in entries:
                    kev_txt = f"KEV yes (added {e['kev_date_added']})" if e["kev_listed"] else "KEV no"
                    epss_txt = ("EPSS not yet scored" if e["epss"] is None
                                else f"EPSS {e['epss']:.5f} (percentile {e['epss_percentile'] * 100:.2f}, dated {e['epss_date']})")
                    report.append(f"{hunt.name}: {e['cve']}: {kev_txt}; {epss_txt}")
            else:
                report.append(f"{hunt.name}: no CVE, no {CONTEXT_NAME}")
        writes[README] = replace_block(README.read_text(encoding="utf-8"), render_table(rows))
    except EpssOutage as exc:
        print(f"error: {exc}. Nothing changed; try again later.", file=sys.stderr)
        return EXIT_EPSS_OUTAGE
    except RefreshError as exc:
        print(f"error: {exc}. Nothing changed.", file=sys.stderr)
        return EXIT_ERROR
    except (OSError, UnicodeDecodeError) as exc:
        print(f"error: could not read a local file: {exc}. Nothing changed.", file=sys.stderr)
        return EXIT_ERROR

    for path, text in writes.items():
        path.write_text(text, encoding="utf-8")
    print("\n".join(report))
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    print(f"KEV catalogue {kev_version}; checked {today}. {len(writes) - 1} hunt file(s) and README table written.")
    return EXIT_OK


def check() -> int:
    fail = 0
    rows = []
    for hunt, cves in collect():
        ctx = hunt / CONTEXT_NAME
        want = expected_cves(hunt)
        if not ctx.exists():
            if want:
                print(f"FAIL {hunt.relative_to(ROOT)}: rule.yml tags or the README CVEs row name "
                      f"{', '.join(want)} but {CONTEXT_NAME} is missing; run the script")
                fail = 1
            rows.append((hunt, []))
            continue
        rel = ctx.relative_to(ROOT)
        text = ctx.read_text(encoding="utf-8")
        try:
            entries = parse_context(text)
        except ValueError as exc:
            print(f"FAIL {rel}: {exc}")
            fail = 1
            continue
        errs = []
        for e in entries:
            errs += validate_entry(e)
        if not errs:
            have = [e["cve"] for e in entries]
            if have != sorted(set(have), key=cve_sort_key):
                errs.append("CVE entries must be unique and in CVE order")
            missing = sorted(set(want) - set(have))
            if missing:
                errs.append(f"rule.yml tags or the README CVEs row name {', '.join(missing)} but the file has no entry; run the script")
            if not entries:
                errs.append("file has no CVE entries; delete it if the hunt has no CVE")
            if render_context(entries) != text:
                errs.append("not in the generated layout; run the script")
        if errs:
            print(f"FAIL {rel}:\n  " + "\n  ".join(errs))
            fail = 1
            continue
        print(f"ok   {rel} ({', '.join(e['cve'] for e in entries)})")
        rows.append((hunt, entries))
    if not fail:
        text = README.read_text(encoding="utf-8")
        try:
            if replace_block(text, render_table(rows)) != text:
                print("FAIL README.md: KEV and EPSS table is out of date; run the script")
                fail = 1
            else:
                print("ok   README.md KEV and EPSS table matches the hunt files")
        except RefreshError as exc:
            print(f"FAIL {exc}")
            fail = 1
    return fail


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="exit codes:\n"
               "  0  success (refresh written, or --check passed)\n"
               "  1  --check found a problem, or a refresh failed; nothing written\n"
               "  2  bad command-line arguments\n"
               "  3  EPSS outage: FIRST returned no score for any CVE; nothing written")
    ap.add_argument("--check", action="store_true", help="validate files offline instead of refreshing (used by CI)")
    ap.add_argument("--allow-null", action="store_true",
                    help="record null when EPSS returns no row, even if the CVE already has a score "
                         "(does not override the outage check, exit code 3)")
    ap.add_argument("--date", help="checked date to record (YYYY-MM-DD); defaults to today in Europe/London")
    args = ap.parse_args()
    if args.check:
        return check()
    today = args.date
    if today is None:
        try:
            from zoneinfo import ZoneInfo
            today = dt.datetime.now(ZoneInfo("Europe/London")).date().isoformat()
        except Exception:  # tz database missing: fall back to UTC
            today = dt.datetime.now(dt.timezone.utc).date().isoformat()
    if not DATE_RE.match(today):
        ap.error("--date must be YYYY-MM-DD")
    return refresh(today, args.allow_null)


if __name__ == "__main__":
    sys.exit(main())
